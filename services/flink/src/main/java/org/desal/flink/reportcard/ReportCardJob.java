package org.desal.flink.reportcard;

import java.nio.charset.StandardCharsets;
import org.apache.flink.api.common.eventtime.WatermarkStrategy;
import org.apache.flink.connector.base.DeliveryGuarantee;
import org.apache.flink.connector.kafka.sink.KafkaRecordSerializationSchema;
import org.apache.flink.connector.kafka.sink.KafkaSink;
import org.apache.flink.connector.kafka.source.KafkaSource;
import org.apache.flink.connector.kafka.source.enumerator.initializer.OffsetsInitializer;
import org.apache.flink.streaming.api.datastream.DataStream;
import org.apache.flink.streaming.api.datastream.SingleOutputStreamOperator;
import org.apache.flink.streaming.api.environment.StreamExecutionEnvironment;
import org.apache.flink.util.function.SerializableFunction;
import org.apache.kafka.clients.consumer.OffsetResetStrategy;
import org.apache.kafka.clients.producer.ProducerRecord;
import org.desal.flink.common.Args;
import org.desal.flink.common.Json;
import org.desal.flink.common.Topics;
import org.desal.flink.model.RunResult;
import org.desal.flink.reportcard.ReportCardFunction.ShiftReportOut;

/**
 * The "report-card" job: plant.events + plant.status, keyed by gameId, into shift.reports (keyed
 * by gameId) and run.results (keyed by runId). Options: {@code --brokers}, {@code --topic-suffix}.
 */
public final class ReportCardJob {
  public static final String JOB_NAME = "report-card";
  public static final String GROUP_ID = "desal-flink-report-card";
  public static final long CHECKPOINT_EVERY_MS = 60_000;

  private ReportCardJob() {}

  public static void main(String[] argv) throws Exception {
    StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
    define(env, Args.parse(argv));
    env.execute(JOB_NAME);
  }

  /** Adds the job's sources, function and sinks to {@code env}. */
  public static void define(StreamExecutionEnvironment env, Args args) {
    // A checkpoint is a consistent snapshot of every operator's state plus the Kafka offsets the
    // sources have read up to, taken every minute. After a failure Flink restores the latest one
    // and re-reads Kafka from those offsets, so no record is lost; some may be processed twice,
    // which the function's (epoch, seq) checks absorb. The sources also commit those offsets to
    // Kafka on each checkpoint, which is where a fresh start (no savepoint) picks up.
    env.enableCheckpointing(CHECKPOINT_EVERY_MS);
    env.setParallelism(1);
    // A savepoint is a checkpoint taken on purpose (deploys stop the job with one and resubmit
    // from it). It maps state to operators by their uid, so every operator gets a fixed uid below;
    // with auto-generated uids off, building the job fails if one is missing.
    env.getConfig().disableAutoGeneratedUIDs();

    // No watermarks: the job orders records by epoch, seq and tick, not by event time.
    DataStream<Input> events = env
        .fromSource(source(args, args.topic(Topics.EVENTS)), WatermarkStrategy.noWatermarks(), "plant.events")
        .uid("plant-events-source").name("plant.events");
    DataStream<Input> status = env
        .fromSource(source(args, args.topic(Topics.STATUS)), WatermarkStrategy.noWatermarks(), "plant.status")
        .uid("plant-status-source").name("plant.status");

    // connect joins two streams of different meaning into one operator with two inputs; keying
    // both by gameId sends a game's events and statuses to the same place and the same state.
    SingleOutputStreamOperator<ShiftReportOut> reports = events
        .connect(status)
        .keyBy(i -> i.gameId, i -> i.gameId)
        .process(new ReportCardFunction())
        .uid("report-card").name("report card");

    reports
        .sinkTo(sink(args, new JsonRecord<>(args.topic(Topics.SHIFT_REPORTS), r -> r.gameId, r -> r.report)))
        .uid("shift-reports-sink").name("shift.reports");
    reports.getSideOutput(ReportCardFunction.RUN_RESULTS)
        .sinkTo(sink(args, new JsonRecord<RunResult>(args.topic(Topics.RUN_RESULTS), r -> r.runId, r -> r)))
        .uid("run-results-sink").name("run.results");
  }

  /**
   * Reads one topic from the offsets the group last committed, or from the end when it has none
   * (the first start): the report card is about live games, not about the topic's history.
   */
  @SuppressWarnings("deprecation") // OffsetResetStrategy is what OffsetsInitializer takes in 5.0.0-2.2
  private static KafkaSource<Input> source(Args args, String topic) {
    return KafkaSource.<Input>builder()
        .setBootstrapServers(args.brokers)
        .setTopics(topic)
        .setGroupId(GROUP_ID)
        .setStartingOffsets(OffsetsInitializer.committedOffsets(OffsetResetStrategy.LATEST))
        .setDeserializer(new Input.Deserializer())
        .build();
  }

  /** At-least-once: a record may be written twice after a failure; consumers keep the latest. */
  private static <T> KafkaSink<T> sink(Args args, KafkaRecordSerializationSchema<T> serializer) {
    return KafkaSink.<T>builder()
        .setBootstrapServers(args.brokers)
        .setRecordSerializer(serializer)
        .setDeliveryGuarantee(DeliveryGuarantee.AT_LEAST_ONCE)
        .build();
  }

  /** Writes {@code value(x)} as JSON to {@code topic} under the key {@code key(x)}. */
  static final class JsonRecord<T> implements KafkaRecordSerializationSchema<T> {
    private final String topic;
    private final SerializableFunction<T, String> key;
    private final SerializableFunction<T, Object> value;

    JsonRecord(String topic, SerializableFunction<T, String> key, SerializableFunction<T, Object> value) {
      this.topic = topic;
      this.key = key;
      this.value = value;
    }

    @Override
    public ProducerRecord<byte[], byte[]> serialize(T element, KafkaSinkContext context, Long timestamp) {
      try {
        return new ProducerRecord<>(topic, key.apply(element).getBytes(StandardCharsets.UTF_8),
            Json.MAPPER.writeValueAsBytes(value.apply(element)));
      } catch (com.fasterxml.jackson.core.JsonProcessingException e) {
        throw new IllegalStateException("cannot write " + element, e);
      }
    }
  }
}
